//! OV5640 Camera Driver
//!
//! This module provides a driver specifically for the OV5640 camera sensor.
//! The OV5640 is a 1/4 inch CMOS image sensor with OmniBSI back-illuminated technology,
//! supporting up to 5 megapixels (2592x1944) resolution with 1.4µm pixel size.
//!
//! ## Key Features
//! - 1/4 inch OmniBSI back-illuminated CMOS sensor
//! - Up to 5MP (2592×1944) resolution
//! - 1.4µm × 1.4µm pixel size
//! - High sensitivity imaging area of 3673.6µm × 2738.4µm
//! - CSP package with 5985µm × 5835µm dimensions
//!
//! ## Power Requirements (Based on OV5640_CSP3_DS_2.01_Ruisipusheng.pdf)
//! - AVDD: 2.6V~3.0V analog power supply (recommended 2.8V)
//! - DVDD: 1.5V±5% digital core power supply
//! - DOVDD: 1.7V~3.0V I/O power supply (recommended 1.8V)
//!
//! ### Power Supply Schemes
//! Two power supply schemes are supported:
//!
//! #### Scheme A (Recommended)
//! - 2 external power supplies
//! - DOVDD = 1.8V, DVDD generated by internal regulator
//! - AVDD = 2.8V
//! - Supports power saving and power down modes
//!
//! #### Scheme B
//! - 3 external power supplies
//! - DOVDD = 2.8V
//! - DVDD = 1.5V (externally supplied)
//! - AVDD = 2.8V
//! - Only supports power down mode for power saving
//!
//! ### Power-Up Sequence
//! Based on "OV5640_Camera_Module_Hardware_Application_Notes" Chapter 4:
//! 1. Pull RESETB low, pull PWDN high
//! 2. Power up DOVDD and AVDD (DOVDD before AVDD)
//! 3. After AVDD stable for 5ms, pull PWDN low
//! 4. After PWDN low for 1ms, pull RESETB high
//! 5. After 20ms, perform SCCB initialization
//!
//! ## Performance Characteristics
//! - Maximum SNR ratio: 36 dB
//! - Dynamic range: 68 dB (at 8x gain)
//! - Sensitivity: 600 mV/Lux-sec
//! - Dark current: 8 mV/s (at 60°C junction temperature)
//!
//! ## Power Management
//! The OV5640 sensor offers power management features to reduce power consumption
//! in battery-powered applications. It's recommended to disable the sensor when
//! not in use to conserve power, following the "use and release" principle.
//!
//! ## Frame Rate Capabilities
//! The OV5640 supports different frame rates depending on the resolution:
//! - 2592x1944 @ 15fps (5M full resolution)
//! - 1920x1080 @ 30fps (1080P HD)
//! - 1280x960 @ 45fps (1.3M)
//! - 1280x720 @ 60fps (720P)
//! - 640x480 @ 90fps (VGA)
//! - 320x240 @ 120fps (QVGA)
//!
//! ## Interface Options
//! The OV5640 supports multiple output interfaces:
//! - DVP: Parallel Digital Video Port
//! - MIPI: Dual-channel MIPI interface
//! - SCCB: Serial Camera Control Bus
//!
//! ### SCCB Interface Characteristics
//! - Clock speed: 400 kHz standard serial clock
//! - Device address: 0x78 (write), 0x79 (read)
//!
//! ## Basic Initialization
//! The basic initialization sequence includes:
//! - System clock configuration
//! - PLL configuration (for 24MHz input clock)
//! - Image size configuration (VGA as an example)
//! - Timing configuration
//! - Image processing function enable
//!
//! ## Image Quality Configuration
//! The image quality configuration includes:
//! - Auto Exposure Control (AEC)
//! - Auto White Balance (AWB)
//! - Color saturation
//! - Gamma correction
//! - Lens correction
//!
//! ## Auto Focus
//! The OV5640 supports auto focus functionality with the following states:
//! - Idle: Waiting for focus command
//! - Scan: Scanning focus area
//! - Focused: Focus completed successfully
//! - Failed: Focus operation failed
//!
//! ## Night Mode
//! The OV5640 supports night mode configuration which enables long exposure times
//! for better low-light performance.
//!
//! ## Mirror and Flip
//! The OV5640 supports horizontal mirror and vertical flip configuration
//! to adjust the image orientation as needed.
//!
//! ## Banding Filter (Flicker Elimination)
//! The OV5640 supports banding filter configuration to eliminate flicker
//! from artificial lighting sources. Supported modes:
//! - Off: Disable banding filter
//! - Manual 50Hz: Manual 50Hz mode
//! - Manual 60Hz: Manual 60Hz mode
//! - Auto: Automatic detection mode
//!
//! ## Hardware Design Considerations
//! When designing hardware with the OV5640, several important considerations should be taken into account:
//! - Power Decoupling: Each power pin requires a 100nF decoupling capacitor placed close to the pin
//! - Ground Separation: Analog ground (AGND) and digital ground (DGND) should be connected at a single point outside the module
//! - Clock Stability: The XCLK clock needs to be stable with jitter less than 1%
//! - Signal Integrity: High-speed signal lines require impedance matching
//!
//! ## Power Saving Modes
//! The OV5640 supports two power saving modes based on DOVDD voltage:
//! - Power Down Mode: Can be used when DOVDD <= 1.8V, DVDD generated by internal regulator
//! - Power Off Mode: Must be used when DOVDD > 1.8V, DVDD must be externally supplied
//!
//! ## LED Flash Functionality
//! The OV5640 supports LED flash functionality through the STROBE pin:
//! - Dedicated STROBE pin (E1) for control
//! - Supports LED flash and xenon flash modes
//! - Maximum current: 200mA (requires external drive circuit)
//! - Response speed: <100μs fast response
//!
//! ### Software Control
//! - Register control via 0x300A, 0x3A20 and other registers
//! - Mode support: Auto flash, manual flash, red-eye reduction, torch mode
//! - Smart algorithms: Automatic power calculation based on ambient light and distance
//!
//! ### Protection Mechanisms
//! - Thermal protection: Flash count and interval limits
//! - Overcurrent protection: Current monitoring and limiting
//! - Life protection: Total flash count statistics
//!
//! ### Advanced Features
//! - Red-eye reduction: Pre-flash + main flash dual pulse sequence
//! - Exposure compensation: Automatic exposure parameter adjustment during flash
//! - Power management: Intelligent charge/discharge control

