        impl PowerScheme {
            /// Get a description of the power scheme
            pub fn description(&self) -> &'static str {
                match self {
                    PowerScheme::SchemeA(_) => "Scheme A: 2 external power supplies (recommended)",
                    PowerScheme::SchemeB(_) => "Scheme B: 3 external power supplies",
                }
            }

            /// Check if internal DVDD regulator is used
            pub fn uses_internal_dvdd(&self) -> bool {
                match self {
                    PowerScheme::SchemeA(_) => true,
                    PowerScheme::SchemeB(_) => false,
                }
            }

            /// Get supported power saving features
            pub fn power_saving_features(&self) -> &'static str {
                match self {
                    PowerScheme::SchemeA(_) => "Supports power saving and power down modes",
                    PowerScheme::SchemeB(_) => "Only supports power down mode for power saving",
                }
            }

            /// Get the recommended power saving mode based on DOVDD voltage
            ///
            /// According to "OV5640_Camera_Module_Hardware_Application_Notes" Chapter 4,
            /// the appropriate power saving mode depends on the DOVDD voltage:
            /// - Power Down Mode: Can be used when DOVDD <= 1.8V, DVDD generated by internal regulator
            /// - Power Off Mode: Must be used when DOVDD > 1.8V, DVDD must be externally supplied
            pub fn recommended_power_saving_mode(&self) -> PowerSavingMode {
                let dovdd_voltage = match self {
                    PowerScheme::SchemeA(scheme) => scheme.dovdd_voltage,
                    PowerScheme::SchemeB(scheme) => scheme.dovdd_voltage,
                };

                if dovdd_voltage <= 1.8 {
                    PowerSavingMode::PowerDown
                } else {
                    PowerSavingMode::PowerOff
                }
            }
        }

