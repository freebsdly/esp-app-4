    /// This function configures the ISP input window by setting registers 0x3800-0x3807.
    /// The ISP input window allows users to set the region of interest within the entire
    /// sensor area (physical pixel size: 2632*1951).
    ///
    /// # Arguments
    /// * `x_start` - X start address (0-2632)
    /// * `y_start` - Y start address (0-1951)
    /// * `x_end` - X end address (0-2632)
    /// * `y_end` - Y end address (0-1951)
