/// OV5640-specific camera configuration
pub struct OV5640Config<'a> {
    /// Base camera configuration
    pub base_config: camera::CameraConfig<'a>,
    /// Sensor-specific settings
    pub sensor_settings: OV5640SensorSettings,
    /// Power scheme configuration
    pub power_scheme: constants::power::PowerScheme,
}

impl Default for OV5640Config<'_> {
    fn default() -> Self {
        Self {
            base_config: camera::CameraConfig::default(),
            sensor_settings: OV5640SensorSettings::default(),
            power_scheme: constants::power::PowerScheme::default(),
        }
    }
}

impl OV5640Config<'_> {
    /// Create a new OV5640 configuration with default settings
    pub fn new() -> Self {
        Self::default()
    }

    /// Create a configuration optimized for high resolution
    pub fn high_resolution() -> Self {
        let mut config = Self::default();
        config.base_config.frame_size = camera::FrameSize::Qxga; // 2592x1944
        config.base_config.pixel_format = camera::PixelFormat::Rgb565;
        config
            .base_config
            .set_jpeg_quality_for_frame_size(camera::FrameSize::Qxga);
        config
    }

    /// Create a configuration optimized for speed/performance
    pub fn performance_optimized() -> Self {
        let mut config = Self::default();
        config.base_config = camera::CameraConfig::psram_optimized();
        config.base_config.frame_size = camera::FrameSize::Vga; // 640x480
        config.base_config.pixel_format = camera::PixelFormat::Rgb565;
        config
            .base_config
            .set_jpeg_quality_for_frame_size(camera::FrameSize::Vga);
        config
    }

    /// Create a configuration optimized for maximum frame rate
    pub fn max_fps(frame_size: camera::FrameSize) -> Self {
        let mut config = Self::default();
        config.base_config.frame_size = frame_size;
        config.base_config.pixel_format = camera::PixelFormat::Rgb565;
        config.base_config.fb_location = camera::FrameBufferLocation::InPsram;
        config.base_config.fb_count = 2; // Double buffering
        config
            .base_config
            .set_jpeg_quality_for_frame_size(frame_size);
        config
    }

    /// Use power scheme A (recommended)
    pub fn with_power_scheme_a() -> Self {
        let mut config = Self::default();
        config.power_scheme =
            constants::power::PowerScheme::SchemeA(constants::power::PowerSchemeA::default());
        config
    }

    /// Use power scheme B
    pub fn with_power_scheme_b() -> Self {
        let mut config = Self::default();
        config.power_scheme =
            constants::power::PowerScheme::SchemeB(constants::power::PowerSchemeB::default());
        config
    }
}

